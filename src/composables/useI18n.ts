export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = locale.value === 'en' ? en : zh
  let s: string | undefined = dict[key]
  // 英文复数：vars.n 为数字时优先找 key_one / key_other
  if (vars && typeof vars.n === 'number') {
    const plural = dict[key + (vars.n === 1 ? '_one' : '_other')]
    if (plural != null) s = plural
  }
  if (s == null) s = zh[key] ?? key
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (_, k: string) =>
      k in vars ? String(vars[k]) : `{${k}}`,
    )
  }
  return s
}

