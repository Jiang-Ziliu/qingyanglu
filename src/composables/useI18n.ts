/**
 * 青阳录 · 轻量国际化（中文 / English）
 * - 不引入第三方库：一份响应式 locale + 两本扁平字典
 * - t('key', vars) 支持 {name} 插值；带数字 n 时自动取 key_one / key_other（英文复数）
 * - tf(中文专有名词) 翻译节气 / 节日 / 生肖；字典里没有的词原样返回
 * - 语言选择存在 localStorage，首次访问按浏览器语言猜测
 */
import { ref } from 'vue'

export type Locale = 'zh' | 'en'

const STORAGE_KEY = 'qyl.locale'

function detect(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'zh' || saved === 'en') return saved
  } catch {
    /* localStorage 不可用时按浏览器语言兜底 */
  }
  return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export const locale = ref<Locale>(detect())

export function setLocale(next: Locale) {
  locale.value = next
  try {
    localStorage.setItem(STORAGE_KEY, next)
  } catch {
    /* 忽略存储失败 */
  }
}

